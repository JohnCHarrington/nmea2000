def decode_pgn_130840(data_raw: int, data_length_bits: int | None = None) -> NMEA2000Message | None:
    # maretronGenericSensor | Description: Maretron: Generic Sensor
    if (
        (((data_raw >> 0) & 0x7FF) == 137) and
        (((data_raw >> 13) & 0x7) == 4)
        ):
        return decode_pgn_130840_maretronGenericSensor(data_raw, data_length_bits)
    
    # simnetDataUserGroupConfiguration | Description: Simnet: Data User Group Configuration
    if (
        (((data_raw >> 0) & 0x7FF) == 1857) and
        (((data_raw >> 13) & 0x7) == 4)
        ):
        return decode_pgn_130840_simnetDataUserGroupConfiguration(data_raw, data_length_bits)
    
    
    return None
    
